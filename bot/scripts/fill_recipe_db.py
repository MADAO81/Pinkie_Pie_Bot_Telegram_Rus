def fill_db():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    for recipe in RECIPES:
        cursor.execute("""
            INSERT INTO recipes (title, category, ingredients, instructions, source)
            VALUES (?, ?, ?, ?, ?)
        """, (
            recipe['title'],
            recipe['category'],
            recipe['ingredients'],
            recipe['instructions'],
            'Пинки Пай'
        ))
    conn.commit()
    conn.close()
    print(f"✅ Добавлено {len(RECIPES)} рецептов в базу")

if __name__ == "__main__":
    fill_db()
